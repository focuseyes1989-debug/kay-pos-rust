const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../crates/pos_desktop/assets/search-autocomplete.js'), 'utf8');
const functions = source.slice(source.indexOf(' const normalize='), source.indexOf(' const visible='));
const {salesScore} = vm.runInNewContext(`(()=>{${functions};return {salesScore};})()`);
assert.equal(salesScore('nestle', 'Nestle Butterfly', 'Nestle Butterfly SKU123'), 1);
assert.equal(salesScore('butter', 'Nestle Butterfly', 'Nestle Butterfly'), 2);
assert.equal(salesScore('neslte', 'Nestle Butterfly', 'Nestle Butterfly'), 4);
assert.equal(salesScore('nestl', 'Nestle Butterfly', 'Nestle Butterfly'), 1);
assert.equal(salesScore('nestel', 'Nestle Butterfly', 'Nestle Butterfly'), 4);
assert.equal(salesScore('sku123', 'Nestle Butterfly', 'Nestle Butterfly sku123'), 2);
assert.equal(salesScore('12345', '12346', '12346'), Infinity, 'Never fuzzy match numeric barcodes');
assert.equal(salesScore('ne', 'Water', 'Water'), Infinity, 'Avoid noisy short-query corrections');
assert.equal(salesScore('camera', 'Singha Water', 'Singha Water'), Infinity);
assert.equal(salesScore('မောင', 'မောင်မောင်', 'မောင်မောင်'), 1);
assert.equal(salesScore('မောန်', 'မောင်', 'မောင်'), 4);
assert(salesScore('nestle', 'Nestle', 'Nestle') < salesScore('nestle', 'Neslte', 'Neslte'));
console.log('Sales suggestions: exact, prefix, SKU, transposition, Unicode, unrelated and numeric queries passed.');
